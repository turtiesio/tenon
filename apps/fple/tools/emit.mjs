// Project the single extracted definition into native Tenon data modules.
import { readFile, writeFile, readdir, mkdir, rm } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const app = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const system = JSON.parse(await readFile(join(app, 'definition/system.json'), 'utf8'));
const check = process.argv.includes('--check');
const outputs = new Map();
const quote = text => JSON.stringify(text).replaceAll('\\u0000', '\\0');
const sourceString = text => quote(text).replaceAll('{', '\\{');
const sequence = items => `[${items.join(', ')}]`;
const strings = items => sequence(items.map(quote));
function value(input) {
  if (input === null) return 'VNull';
  if (typeof input === 'boolean') return `VBool(${input})`;
  if (typeof input === 'string') return `VText(${quote(input)})`;
  if (typeof input === 'number') return Number.isInteger(input) ? `VInt(${input})` : `VDecimal(${input})`;
  if (Array.isArray(input)) return `VList(${sequence(input.map(value))})`;
  const entries = Object.entries(input).map(([key, item]) => `${quote(key)}: ${value(item)}`);
  return `VObject(${entries.length ? sequence(entries) : '[:]'})`;
}
function record(name, fields) { return `${name} { ${Object.entries(fields).map(([key, item]) => `${key}: ${item}`).join(', ')} }`; }
function operation(op) {
  let access = op.access?.kind ?? 'permit';
  if (access === 'actor') access = op.access.mode;
  return record('Operation', {
    id: quote(op.id), owner: quote(op.owner), kind: quote(op.kind), version: op.definitionVersion,
    idempotency: quote(op.idempotency), access: quote(access), scope_kind: quote(op.scope?.name ?? ''),
    scope_field: quote(op.scope?.objectIdField ?? ''), scope_schema: op.scope?.schema ?? -1,
    permission: quote(op.permission ?? ''), input_schema: op.inputSchema, output_schema: op.outputSchema,
    reads: strings(op.readEntities ?? []), writes: strings(op.writeEntities ?? []), events: strings(op.emittedEvents ?? []),
    ports: strings(op.ports ?? []), guards: strings(op.guards ?? []), invalidates: strings(op.invalidates ?? []),
    cache: value(op.clientCache ?? {}), input_validation: sequence((op.inputValidation ?? []).map(value)),
    output_validation: sequence((op.outputValidation ?? []).map(value)), source: quote(op.source),
  });
}
const header = '// @generated by apps/fple/tools/emit.mjs from definition/system.json.\n// Data only; no action implementation is inferred from these contracts.\nimport fple_model\n\n';
function emitRows(name, type, rows) {
  const file = `fple_data_${name}.tn`;
  const source = header + `pub fn load() -> Result[List[fple_model.${type}], Str] {\n    decode(${sourceString(sequence(rows))})\n}\n`;
  outputs.set(file, source);
  return `fple_data_${name}`;
}
const schemaModules = [];
for (let i = 0; i < system.schemas.length; i += 128) schemaModules.push(emitRows(`schemas_${i / 128}`, 'Value', system.schemas.slice(i, i + 128).map(value)));
const operationModules = [];
for (const owner of [...new Set(system.operations.map(op => op.owner))].sort()) operationModules.push(emitRows(owner.replaceAll('-', '_'), 'Operation', system.operations.filter(op => op.owner === owner).map(operation)));
const routeModule = emitRows('routes', 'HttpRoute', system.routes.map(route => record('HttpRoute', {
  key: quote(route.key), path: quote(route.routePath), methods: strings(route.methods), principal: value(route.principal),
  policy: value(Object.fromEntries(Object.entries(route).filter(([key]) => !['key','routePath','methods','principal','operationRefs'].includes(key)))),
  operations: strings(route.operationRefs ?? []),
})));
const pageModule = emitRows('pages', 'Page', system.screens.map(page => record('Page', { path: quote(page.path), source: quote(page.file), operations: strings(page.operations) })));
const roleModule = emitRows('roles', 'RoleDefault', Object.entries(system.roles).flatMap(([scope, roles]) => roles.map(role => record('RoleDefault', {
  scope: quote(scope === 'seller' ? 'seller.account' : 'platform'), key: quote(role.key), label: quote(role.label),
  permissions: strings(role.permissions), system: String(role.system),
}))));
const entityModule = emitRows('entities', 'EntitySpec', system.entities.map(entity => record('EntitySpec', {
  name: quote(entity.name), schema: entity.schema, immutable: strings(entity.immutable), indexes: sequence(entity.indexes.map(value)),
  uniqueness: sequence(entity.unique.map(value)), invariants: sequence(entity.invariants.map(value)), version: entity.schemaVersion, validation: sequence(entity.validation.map(value)),
})));
const signalModule = emitRows('signals', 'SignalSpec', system.signals.map(signal => record('SignalSpec', { name: quote(signal.name), schema: signal.schema, validation: sequence(signal.validation.map(value)), metadata: value(signal.metadata) })));
const portModule = emitRows('ports', 'PortSpec', system.hostPorts.map(port => record('PortSpec', { name: quote(port.name), input_schema: port.inputSchema, output_schema: port.outputSchema,
  input_validation: sequence(port.inputValidation.map(value)), output_validation: sequence(port.outputValidation.map(value)) })));
const imports = [...schemaModules, ...operationModules, routeModule, pageModule, roleModule, entityModule, signalModule, portModule];
outputs.set('fple_catalog.tn', '// @generated by apps/fple/tools/emit.mjs.\nimport fple_model\n' + imports.map(name => `import ${name}`).join('\n') + `

pub fn load() -> Result[fple_model.Catalog, Str] {
    var schemas: List[fple_model.Value] = []
${schemaModules.map(name => `    schemas.extend(${name}.load()?)`).join('\n')}
    var operations: List[fple_model.Operation] = []
${operationModules.map(name => `    operations.extend(${name}.load()?)`).join('\n')}
    Ok(fple_model.Catalog { schemas, operations, routes: ${routeModule}.load()?,
        pages: ${pageModule}.load()?, roles: ${roleModule}.load()?,
        source_revision: ${sourceString(system.sourceRevision)}, source_digest: ${sourceString(system.sourceDigest)},
        entities: ${entityModule}.load()?, signals: ${signalModule}.load()?, host_ports: ${portModule}.load()? })
}
`);
await mkdir(join(app, 'src'), { recursive: true });
for (const file of await readdir(join(app, 'src'))) {
  if (file.startsWith('fple_data_') && file.endsWith('.tn') && !outputs.has(file)) {
    if (check) throw new Error(`Obsolete generated module: ${file}`);
    await rm(join(app, 'src', file));
  }
}
for (const [file, source] of outputs) {
  const target = join(app, 'src', file);
  if (check) {
    if (await readFile(target, 'utf8') !== source) throw new Error(`Stale generated module: ${file}`);
  } else await writeFile(target, source);
}
console.log(`Tenon definition: ${system.operations.length} operations, ${system.routes.length} HTTP routes, ${system.screens.length} pages, ${system.schemas.length} shared schema nodes`);
